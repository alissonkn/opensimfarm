"""make_icon.py import SRC.png   - takes a new master icon (square RGBA PNG): stored as packaging/opensimfarm.png
                                   (512 x 512, invisible pixels cleared), then the generated files are rebuilt
   make_icon.py generate         - rebuilds the generated files from packaging/opensimfarm.png:
                                   packaging/windows/opensimfarm.ico (16-256, for the exe and the installer) and
                                   src/ui/AppIcon.h (64 x 64 RGBA, the game window's icon)
   make_icon.py sizes OUTDIR     - writes OUTDIR/opensimfarm-N.png for N = 16 24 32 48 64 128 256 (Linux packages)
The icon is the project's own (drawn for OpenSimFarm by the user, 2026-11-06). Needs Pillow."""
import os
import sys

from PIL import Image

ENGINE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MASTER = os.path.join(ENGINE, "packaging", "opensimfarm.png")
ICO = os.path.join(ENGINE, "packaging", "windows", "opensimfarm.ico")
HEADER = os.path.join(ENGINE, "src", "ui", "AppIcon.h")
SIZES = [16, 24, 32, 48, 64, 128, 256]


def master():
    return Image.open(MASTER).convert("RGBA")


def import_master(src):
    im = Image.open(src).convert("RGBA")
    if im.width != im.height:
        raise SystemExit("the icon must be square")
    # pixels with almost no cover (alpha below 8) are invisible noise: cleared, so no viewer shows specks
    px = im.load()
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = px[x, y]
            if a < 8:
                px[x, y] = (0, 0, 0, 0)
    im.resize((512, 512), Image.LANCZOS).save(MASTER, optimize=True)


def generate():
    im = master()
    im.resize((256, 256), Image.LANCZOS).save(ICO, sizes=[(n, n) for n in SIZES])
    small = im.resize((64, 64), Image.LANCZOS)
    data = small.tobytes()  # R G B A per pixel, rows from the top
    lines = []
    for i in range(0, len(data), 32):
        lines.append("    " + ",".join("0x%02x" % b for b in data[i:i + 32]) + ",")
    with open(HEADER, "w") as f:
        f.write("// OpenSimFarm - an open re-implementation of SimFarm. Copyright (c) 2026 OpenSimFarm developers.\n")
        f.write("// Licensed under the GNU General Public License version 3 (see LICENSE.txt).\n")
        f.write("// Generated by tools/make_icon.py from packaging/opensimfarm.png - do not edit.\n")
        f.write("#pragma once\n#include <cstdint>\n\nnamespace osf {\n\n")
        f.write("// the game window's icon: 64 x 64 pixels, 4 bytes each (red, green, blue, alpha), rows from the top\n")
        f.write("constexpr int kAppIconSize = 64;\n")
        f.write("inline constexpr uint8_t kAppIcon[kAppIconSize * kAppIconSize * 4] = {\n")
        f.write("\n".join(lines) + "\n};\n\n} // namespace osf\n")


def sizes(out):
    os.makedirs(out, exist_ok=True)
    im = master()
    for n in SIZES:
        im.resize((n, n), Image.LANCZOS).save(os.path.join(out, "opensimfarm-%d.png" % n), optimize=True)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "import":
        import_master(sys.argv[2])
        generate()
    elif len(sys.argv) == 2 and sys.argv[1] == "generate":
        generate()
    elif len(sys.argv) == 3 and sys.argv[1] == "sizes":
        sizes(sys.argv[2])
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
